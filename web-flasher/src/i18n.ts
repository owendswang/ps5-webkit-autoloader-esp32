let language: Language = document.documentElement.lang.startsWith('zh') ? 'zh' : 'en'

export function setLanguage(next: Language) {
  language = next
  document.documentElement.lang = next === 'zh' ? 'zh-CN' : 'en'
}

export function t(key: string, values: Values = {}) {
  const text = (language === 'zh' ? chinese[key] : english[key]) ?? english[key] ?? key
  return text.replace(/\{(\w+)\}/g, (match, name: string) => String(values[name] ?? match))
}

export function translatePage() {
  // Only authored dictionary entries are rendered as markup. Runtime values use textContent.
  document.querySelectorAll<HTMLElement>('[data-i18n]').forEach(element => {
    element.innerHTML = t(element.dataset.i18n!)
    if (element.classList.contains('mo-wh__text')) element.removeAttribute('aria-label')
  })
  document.querySelectorAll<HTMLElement>('[data-i18n-aria]').forEach(element => {
    element.setAttribute('aria-label', t(element.dataset.i18nAria!))
  })
  document.title = t('pageTitle')
  document.querySelector('meta[name="description"]')?.setAttribute('content', t('pageDescription'))
  document.querySelector('meta[property="og:title"]')?.setAttribute('content', t('pageTitle'))
  document.querySelector('meta[property="og:description"]')?.setAttribute('content', t('pageDescription'))
}
